"""Rebuild the flash-resident web pages after editing data/. No filesystem upload needed."""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
parts = ["// Generated by tools/embed_web_assets.py; edit data/ instead.\n#pragma once\n#include <Arduino.h>\n"]
for name, filename in [("INDEX", "index.html"), ("APP", "app.js"), ("STYLE", "style.css")]:
    content = (root / "data" / filename).read_text(encoding="utf-8")
    assert ')HELTEC_WEB"' not in content
    parts.append('static const char WEB_' + name + '[] PROGMEM = R"HELTEC_WEB(' + content + ')HELTEC_WEB";\n')
(root / "WebAssets.h").write_text("".join(parts), encoding="utf-8")
print("Embedded offline web assets in WebAssets.h")
